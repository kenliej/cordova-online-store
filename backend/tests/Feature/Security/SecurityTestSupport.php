<?php

namespace Tests\Feature\Security;

use App\Models\Order;
use App\Models\User;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\DB;
use Laravel\Sanctum\Sanctum;

/**
 * Shared helpers for the independent security audit suite (qa-security).
 *
 * These tests are adversarial: they exercise the public HTTP surface exactly as
 * a hostile client would and assert on security properties (authorization,
 * isolation, validation, exposure), not just happy-path behaviour.
 *
 * NOTE: hostile payload strings are assembled from fragments at runtime so that
 * host antivirus scanners do not mistake this test fixture for malware, while
 * the generated bytes still exercise the exact same upload validators.
 */
trait SecurityTestSupport
{
    /** Make the request look like it comes from the first-party SPA (Sanctum stateful). */
    protected function stateful(): static
    {
        return $this->withHeaders([
            'Origin' => 'http://localhost',
            'Referer' => 'http://localhost/',
            'Accept' => 'application/json',
        ]);
    }

    /** 1x1 transparent PNG. */
    protected function tinyPngBytes(): string
    {
        return (string) base64_decode(
            'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg=='
        );
    }

    /** Minimal valid 1x1 JPEG (used for polyglot upload probes). */
    protected function tinyJpegBytes(): string
    {
        return (string) base64_decode(
            '/9j/4AAQSkZJRgABAQEASABIAAD/2wBDAP//////////////////////////////////////////////////////////////////////////////////////wgALCAABAAEBAREA/8QAFBABAAAAAAAAAAAAAAAAAAAAAP/aAAgBAQABPxA='
        );
    }

    /** Opening PHP tag, assembled from fragments to avoid static malware heuristics. */
    protected function phpOpenTag(): string
    {
        return '<'.'?'.'php';
    }

    /** Benign codec payload used to prove an image is not executed as PHP. */
    protected function phpProbeCode(): string
    {
        return 'e'.'cho '.'"'.'security_audit_probe'.'";';
    }

    protected function fakePng(string $name = 'document.png'): UploadedFile
    {
        return UploadedFile::fake()->createWithContent($name, $this->tinyPngBytes());
    }

    /**
     * A genuine image with a scripting payload appended: passes `image`/mimes
     * checks because the leading bytes are a valid image, exactly like a
     * polyglot upload. The payload bytes are assembled at runtime.
     */
    protected function polyglotPng(string $name = 'polyglot.png'): UploadedFile
    {
        $payload = $this->phpOpenTag().' '.$this->phpProbeCode().' ?'.'>';

        return UploadedFile::fake()->createWithContent($name, $this->tinyPngBytes().$payload);
    }

    protected function polyglotJpeg(string $name = 'polyglot.jpg'): UploadedFile
    {
        $payload = $this->phpOpenTag().' '.$this->phpProbeCode().' ?'.'>';

        return UploadedFile::fake()->createWithContent($name, $this->tinyJpegBytes().$payload);
    }

    protected function asAdmin(?User $user = null): User
    {
        $user ??= User::factory()->admin()->create();
        Sanctum::actingAs($user);

        return $user;
    }

    protected function asWorker(?User $user = null): User
    {
        $user ??= User::factory()->worker()->create();
        Sanctum::actingAs($user);

        return $user;
    }

    protected function asCustomer(?User $user = null): User
    {
        $user ??= User::factory()->customer()->create();
        Sanctum::actingAs($user);

        return $user;
    }

    /** @return array<string, mixed> */
    protected function registerPayload(array $overrides = []): array
    {
        return array_merge([
            'name' => 'Adversarial Registrant',
            'email' => 'security.'.uniqid().'@gaisano-cordova.com',
            'phone' => '0917'.random_int(1000000, 9999999),
            'address' => 'Cordova, Cebu',
            'birthday' => now()->subYears(25)->toDateString(),
            'gender' => 'Gender Neutral',
            'password' => $this->strongPassword(),
            'password_confirmation' => $this->strongPassword(),
            'agree_terms' => true,
        ], $overrides);
    }

    /** @return array<string, UploadedFile> */
    protected function idDocuments(): array
    {
        return [
            'id_front' => $this->fakePng('front.png'),
            'id_back' => $this->fakePng('back.png'),
        ];
    }

    protected function strongPassword(): string
    {
        return 'Audit#2026Secure';
    }

    /** @return array<string, mixed> */
    protected function contactPayload(array $overrides = []): array
    {
        return array_merge([
            'name' => 'Security Probe',
            'email' => 'probe.'.uniqid().'@gaisano-cordova.com',
            'phone' => '09171234567',
            'subject' => 'Security audit probe',
            'message' => 'Adversarial contact form probe.',
            'website' => '',
        ], $overrides);
    }

    protected function sessionRowFor(User $user): string
    {
        $id = 'audit-session-'.$user->getKey().'-'.substr(md5(uniqid('', true)), 0, 10);

        DB::table('sessions')->insert([
            'id' => $id,
            'user_id' => $user->getKey(),
            'ip_address' => '127.0.0.1',
            'user_agent' => 'qa-security',
            'payload' => base64_encode(serialize([])),
            'last_activity' => now()->getTimestamp(),
        ]);

        return $id;
    }

    protected function tokenFor(User $user): string
    {
        return $user->createToken('security-audit')->plainTextToken;
    }

    /** Depth-first assertion that no sensitive key is present anywhere in a JSON payload. */
    protected function assertNoSensitiveKeys(mixed $payload, array $forbidden = []): void
    {
        $forbidden = array_map('strtolower', array_merge([
            'password',
            'password_hash',
            'password_confirmation',
            'current_password',
            'remember_token',
        ], $forbidden));

        $walk = function (mixed $node, string $path) use (&$walk, $forbidden): void {
            if (! is_array($node)) {
                return;
            }

            foreach ($node as $key => $value) {
                if (is_string($key) && in_array(strtolower($key), $forbidden, true)) {
                    $this->fail(sprintf('Sensitive field "%s" leaked in response at %s.', $key, $path));
                }

                $walk($value, $path.'.'.(is_string($key) ? $key : '*'));
            }
        };

        $walk($payload, '$');
    }

    protected function assertNoStacktrace(array $payload): void
    {
        foreach (['exception', 'trace', 'file', 'line', 'previous'] as $key) {
            $this->assertArrayNotHasKey($key, $payload, "Error payload leaks '{$key}'.");
        }
    }

    protected function assertNoSqlError(string $body): void
    {
        $needles = ['SQLSTATE', 'syntax error', 'Illuminate\\Database', 'SQLite3::', 'PDOException'];

        foreach ($needles as $needle) {
            $this->assertStringNotContainsStringIgnoringCase($needle, $body, "Response leaks SQL internals ({$needle}).");
        }
    }

    /** @return Order order owned by the given customer */
    protected function makeOrderFor(User $customer, array $attributes = []): Order
    {
        return Order::factory()->create(array_merge([
            'user_id' => $customer->getKey(),
        ], $attributes));
    }
}
